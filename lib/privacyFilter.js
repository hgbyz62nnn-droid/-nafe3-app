// فلتر بسيط بيكشف محاولات مشاركة أرقام موبايل أو حسابات تواصل جوه الشات.
// ملاحظة مهمة: ده فلتر أساسي (regex) وسهل التحايل عليه (زي كتابة الرقم بمسافات
// أو بالحروف). لو هتشتغل عليه جدي، فكّر في طبقة تانية أذكى تحلل الرسالة بمعنى
// أشمل، مش بس نمط نصي.

const PATTERNS = [
  /(?:\+?\d[\s\-.]?){9,}/, // أي تسلسل أرقام طويل يشبه رقم تليفون
  /01[0125][\s\-]?\d[\s\-]?\d{3}[\s\-]?\d{4}/, // نمط رقم موبايل مصري
  /@[a-zA-Z0-9_.]{3,}/, // @handle
  /(whatsapp|واتساب|واتس|انستا|instagram|فيسبوك|facebook|فون|رقمي|رقمى|تليجرام|telegram|snapchat|سناب)/i,
];

function containsContactInfo(text) {
  return PATTERNS.some((p) => p.test(text));
}

module.exports = { containsContactInfo };
