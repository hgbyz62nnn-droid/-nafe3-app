function getLang() {
  try {
    return localStorage.getItem('lang') === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}

function setLang(lang) {
  try { localStorage.setItem('lang', lang); } catch {}
  applyLangAttrs(lang);
}

function applyLangAttrs(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
}

function t(key, vars) {
  const lang = getLang();
  let str = (translations[lang] && translations[lang][key]) || translations.ar[key] || key;
  if (vars) {
    for (const k in vars) str = str.replace(`{${k}}`, vars[k]);
  }
  return str;
}
